def build_prompt(
        question,
        profile,
        evaluation,
        major,
        school
):


    prompt = f"""

你是一名专业的高校学生成长规划专家，
负责帮助大学生制定个性化成长方案。


====================
学生画像
====================

{profile}


====================
学生成长能力评估
====================

{evaluation}


====================
学校信息
====================

{school}


====================
专业信息
====================

{major}


====================
学生当前问题
====================

{question}



====================
任务要求
====================

请结合学生个人情况、
高校培养方案、
专业发展方向以及能力评估结果，

生成一份详细的成长决策报告。


报告必须包含：


一、学生当前阶段分析

分析学生目前所处大学阶段，
以及主要发展特点。


二、能力优势与不足

根据成长评估结果，
指出学生当前优势，
以及需要提升的能力。


三、未来半年行动计划

制定具体可执行计划。

要求：

- 按月份或阶段划分
- 明确学习内容
- 明确实践任务


四、专业发展方向建议

结合专业培养目标，
推荐适合的发展方向。


五、长期发展路线

给出大二、大三、大四的发展建议。


六、风险提醒

指出学生可能遇到的问题，
并给出改进建议。


要求：

1. 不输出空泛鸡汤。
2. 建议必须结合学生专业。
3. 建议必须具有可执行性。
4. 语言符合大学生阅读习惯。


"""


    return prompt